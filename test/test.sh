export PATH="${DIR}/../bin:$PATH"
GO_BIN="${DIR}/../bin/go"
cd "$DIR" || exit 1

RESULTS=()
FAILED_TO_RUN_TESTS=()
SKIPPED_TESTS=()

rm -f failures.txt

# Keep this run independent of other projects and concurrent test runs.
test_cache=$(mktemp -d "${TMPDIR:-/tmp}/tangollvm-testdir.XXXXXX") || exit 1
trap 'rm -rf "$test_cache"' EXIT
export GOCACHE="$test_cache/cache"

unset GO_GCFLAGS
if ! timeout 600s "$GO_BIN" test -c -o "$test_cache/testdir.bin" cmd/internal/testdir; then
    echo "----------> Failed to build the testdir runner" > failures.txt
    exit 1
fi

export TANGO_LLVM_TEST=1
export TANGO_GCFLAGS="$GCFLAGS"
export GOEXPERIMENT=tangollvm

for T in "${TESTS[@]}"
do
    test_file="${T%.go}.go"
    if [[ ! -f "$DIR/$test_file" ]]; then
        RESULTS+=("$T ...FAILED: test file does not exist")
        FAILED_TO_RUN_TESTS+=("$T")
        continue
    fi
    # Go matches each slash-separated test name component independently.
    pattern=$(printf '%s' "$test_file" | sed 's/[][\\.^$*+?(){}|]/\\&/g; s,/,\$/^,g')
    echo "Run tests $test_file (GO_GCFLAGS=$TANGO_GCFLAGS)"
    timeout 600s "$test_cache/testdir.bin" -test.v -test.run="^Test$/^${pattern}$" > "$test_cache/output.log" 2>&1
    status=$?
    cat "$test_cache/output.log"

    if (( status != 0 )); then
        RESULTS+=("$T ...FAILED")
        FAILED_TO_RUN_TESTS+=("$T")
    elif grep -Fq -- "--- PASS: Test/$test_file " "$test_cache/output.log"; then
        RESULTS+=("$T ...passed")
    elif grep -Fq -- "--- SKIP: Test/$test_file " "$test_cache/output.log"; then
        RESULTS+=("$T ...SKIPPED")
        SKIPPED_TESTS+=("$T")
    else
        RESULTS+=("$T ...FAILED: no matching test result")
        FAILED_TO_RUN_TESTS+=("$T")
    fi
done

export TANGO_LLVM_TEST=0

echo "============="
for R in "${RESULTS[@]}"
do
    echo "$R"
done
echo "============="

if [ ${#FAILED_TO_RUN_TESTS[@]} -eq 0 ]; then
    if [ ${#SKIPPED_TESTS[@]} -eq 0 ]; then
        echo "----------> ALL TESTS GOT PASSED" >> failures.txt
    else
        echo "----------> All selected tests passed or were skipped" >> failures.txt
        printf 'SKIPPED: %s\n' "${SKIPPED_TESTS[@]}" >> failures.txt
    fi
    exit 0
fi

if [ ${#FAILED_TO_RUN_TESTS[@]} -ne 0 ]; then
    echo "----------> Failed to run tests:" >> failures.txt
    for R in "${FAILED_TO_RUN_TESTS[@]}"
    do
        echo "$R" >> failures.txt
    done
fi

exit 1
