var (
	// The sequence number of the packages in rcPackages needs to be consistent
	// with the size of the value of replaceFunc in runtime/typetoytype.go
	rcPackages    = []string{"", "github.com/mohae/deepcopy", "github.com/jinzhu/copier"}
	rcFunctions   = []string{"(*Converter).TypeToType", "Copy", "CopyWithOption"}
	rcFunctionMap map[string]int
)

func init() {
	rcFunctionMap = make(map[string]int, len(rcFunctions))
	for i := range rcFunctions {
		rcFunctionMap[rcFunctions[i]] = i
	}
}

func ReplaceConv() {
	if base.Flag.Cfg.BeastOpt.Conv == 0 {
		return
	}
	// During the "walk", new global functions will be added to typecheck.Target.Decls.
	// Here, we use the range expression to prevent iterating over the newly added global functions.
	for _, n := range typecheck.Target.Funcs {
		if n.Op() != ir.ODCLFUNC {
			continue
		}
		ir.CurFunc = n
		ir.Visit(n, func(node ir.Node) {
			call, ok := node.(*ir.CallExpr)
			if !ok {
				return
			}
			if call.Fun == nil {
				return
			}
			var fn *ir.Func
			switch call.Fun.Op() {
			case ir.OMETHEXPR: // (*Converter).TypeToType
				se := call.Fun.(*ir.SelectorExpr)
				name := ir.MethodExprName(se)
				if name != nil && types.Identical(name.Type().Recv().Type, se.X.Type()) {
					fn = name.Func
				}
			case ir.ONAME: // copier.CopyWithOption && deepcopy.Copy
				name := call.Fun.(*ir.Name).Canonical()
				if name.Class == ir.PFUNC {
					fn = name.Func
				}
			}
			if fn == nil {
				return
			}
			idx := rcHitReplacement(fn)
			if idx == -1 {
				return
			}
			var conv *ir.CallExpr
			switch fn.Sym().Name {
			case "Copy":
				if len(call.Args) != 1 || call.Args[0].Type().Kind() != types.TINTER ||
					call.Type().Kind() != types.TINTER {
					return
				}
				// Replace deepcopy.Copy(src) with
				// .tcDeepCopyWrapper(src).
				deepCopyWrapper := rcGetDeepCopyWrapper(fn)
				if deepCopyWrapper == nil {
					return
				}
				conv = typecheck.Call(call.Pos(), deepCopyWrapper.Nname, call.Args, false).(*ir.CallExpr)
			case "CopyWithOption":
				if len(call.Args) != 3 || call.Args[0].Type().Kind() != types.TINTER ||
					call.Args[1].Type().Kind() != types.TINTER ||
					call.Args[2].Type().Kind() != types.TSTRUCT ||
					call.Type().Kind() != types.TINTER {
					return
				}
				// Replace copier.CopyWithOption(dst, src, option) with
				// .tcCopierWrapper(dst, src, option).
				copierWrapper := rcGetCopierWrapper(fn, call.Args)
				if copierWrapper == nil {
					return
				}
				conv = typecheck.Call(call.Pos(), copierWrapper.Nname, call.Args, false).(*ir.CallExpr)
			case "(*Converter).TypeToType":
				if len(call.Args) != 3 || call.Args[0].Type().Kind() != types.TPTR ||
					call.Args[1].Type().Kind() != types.TINTER ||
					call.Args[2].Type().Kind() != types.TINTER ||
					call.Type().Kind() != types.TINTER {
					return
				}
				// Replace mapconv.(*Converter).TypeToType(src, dst) with
				// tcTypeToType(src, dst, !(*Converter).skipDeepCopy, tcTangoConv).
				cvt := call.Args[0]
				skipDeepCopy := rcFindField(cvt.Type().Elem().PtrTo(), "skipDeepCopy")
				if skipDeepCopy == nil {
					return
				}
				deepCopy := ir.NewUnaryExpr(call.Pos(), ir.ONOT,
					ir.NewSelectorExpr(cvt.Pos(), ir.ODOT, cvt, skipDeepCopy))
				replaceFunc := ir.NewBasicLit(call.Pos(), types.Types[types.TUINT8],
					constant.MakeUint64(uint64(idx)))
				conv = typecheck.Call(call.Pos(), typecheck.LookupRuntime("tcTypeToType"),
					append(call.Args[1:], deepCopy, replaceFunc), false).(*ir.CallExpr)
			default:
				return
			}
			call.Fun = conv.Fun
			call.Args = conv.Args
			call.SetInit(conv.Init())
			if base.Flag.LowerM != 0 {
				base.WarnfAt(call.Pos(), "call to %s.%s is replaced with tango/conv at compile time",
					rcPackages[idx], fn.Sym().Name)
			}
		})
	}
}

func rcBuilder(pos src.XPos, src []*types.Field) []*types.Field {
	res := make([]*types.Field, len(src))
	for i := 0; i < len(res); i++ {
		p := src[i]
		// Parameters are all named, but the return value is not necessarily named.
		// A default name is given to the return value here.
		name := typecheck.LookupNum("~r", i).Name
		if p.Sym != nil {
			name = p.Sym.Name
		}
		res[i] = types.NewField(pos, typecheck.Lookup(name), p.Type)
	}
	return res

}

func rcGenerateFuncDecl(fn *ir.Func, fName string) *ir.Func {
	params := rcBuilder(fn.Pos(), fn.Type().Params())
	results := rcBuilder(fn.Pos(), fn.Type().Results())
	fnWarpper := ir.NewFunc(base.AutogeneratedPos, base.AutogeneratedPos, typecheck.Lookup(fName), types.NewSignature(nil, params, results))
	typecheck.DeclFunc(fnWarpper)
	return ir.CurFunc
}

func rcFinishGeneration(deepCopyWrapper *ir.Func, sym *types.Sym) {
	// The code here is from MakeInit.
	typecheck.FinishFuncBody()
	ir.WithFunc(deepCopyWrapper, func() {
		typecheck.Stmts(deepCopyWrapper.Body)
	})

	sym.Def = deepCopyWrapper.Nname
}

func rcCanApplyOptToCopier(callArg []ir.Node) *types.Sym {
	dstConv, ok := callArg[0].(*ir.ConvExpr)
	if !ok {
		return nil
	}
	srcConv, ok := callArg[1].(*ir.ConvExpr)
	if !ok {
		return nil
	}
	typDst := dstConv.X.Type()
	typSrc := srcConv.X.Type()
	typDst = rcDerefPtrType(typDst)
	if typDst == nil {
		return nil
	}
	typSrc = rcDerefPtrType(typSrc)
	if typSrc == nil {
		return nil
	}
	// Only handle the following scenarios:
	// typeSrc is not of the interface type， and at the same time,
	// typeDst is of the interface type, or typeDst is not of the interface type but has the same type as typeSrc.
	if typSrc.IsInterface() {
		return nil
	}
	if typDst != typSrc && !typDst.IsInterface() {
		return nil
	}
	return rcFindField(callArg[2].Type().PtrTo(), "DeepCopy")
}

func rcFindField(typ *types.Type, field string) *types.Sym {
	if !typ.IsPtr() {
		return nil
	}
	typ = typ.Elem()
	if !typ.IsStruct() {
		return nil
	}
	for _, candidate := range typ.Fields() {
		if candidate.Sym.Name == field {
			return candidate.Sym
		}
	}
	return nil
}

func rcDerefPtrType(typDst *types.Type) *types.Type {
	// To prevent cases like type A *A (i.e., self-referential pointer types), an upper limit is set here.
	maxDerefCount := 10
	// We only handle one layer of pointers because there may be special cases like ‘type A *A’.
	// If we handle multiple layers of pointers, a dead loop might occur.
	i := 0
	for ; i < maxDerefCount && typDst.IsPtr(); i++ {
		typDst = typDst.Elem()
	}
	if i == maxDerefCount {
		return nil
	}
	return typDst
}

// rcGetCopierWrapper returns function .tcCopierWrapper(dst, src interface{}, option copier.Option)
// If the function does not exist in the package being compiled, we will generate it.
func rcGetCopierWrapper(fn *ir.Func, callArg ir.Nodes) *ir.Func {
	fName := ".tcCopierWrapper"
	sym := typecheck.Lookup(fName)
	if n := sym.Def; n != nil {
		return n.(*ir.Name).Func
	}

	deepCopy := rcCanApplyOptToCopier(callArg)
	if deepCopy == nil {
		return nil
	}
	ignoreEmpty := rcFindField(callArg[2].Type().PtrTo(), "IgnoreEmpty")
	if ignoreEmpty == nil {
		return nil
	}
	// if !option.DeepCopy || option.IgnoreEmpty || tcTypeToType(src, dst, true) != nil {
	//   return copier.CopyWithOption(dst, src, option)
	// }
	// return nil
	copierWrapper := rcGenerateFuncDecl(fn, fName)
	po := ir.ParamNames(copierWrapper.Nname.Type())
	nilExpr := ir.NewNilExpr(fn.Pos(), types.ErrorType)
	replaceFunc := ir.NewBasicLit(fn.Pos(), types.Types[types.TUINT8],
		constant.MakeUint64(uint64(rcFunctionMap[fn.Sym().Name])))
	needFallback := ir.NewLogicalExpr(fn.Pos(), ir.OOROR,
		ir.NewUnaryExpr(fn.Pos(), ir.ONOT, ir.NewSelectorExpr(fn.Pos(), ir.ODOT, po[2], deepCopy)),
		ir.NewSelectorExpr(fn.Pos(), ir.ODOT, po[2], ignoreEmpty))
	needFallback = ir.NewLogicalExpr(fn.Pos(), ir.OOROR, needFallback,
		ir.NewBinaryExpr(fn.Pos(), ir.ONE, typecheck.Call(fn.Pos(), typecheck.LookupRuntime("tcTypeToType"),
			[]ir.Node{po[1], po[0], ir.NewBool(fn.Pos(), true), replaceFunc}, false), nilExpr))
	ifs := ir.NewIfStmt(fn.Pos(), needFallback, []ir.Node{ir.NewReturnStmt(fn.Pos(),
		[]ir.Node{typecheck.Call(fn.Pos(), fn.Nname, po, false)})}, nil)
	copierWrapper.Body = []ir.Node{ifs, ir.NewReturnStmt(fn.Pos(), []ir.Node{nilExpr})}

	rcFinishGeneration(copierWrapper, sym)
	return copierWrapper
}

// rcGetDeepCopyWrapper returns function .tcDeepCopyWrapper(src)
// If the function does not exist in the package being compiled, we will generate it.
func rcGetDeepCopyWrapper(fn *ir.Func) *ir.Func {
	fName := ".tcDeepCopyWrapper"
	sym := typecheck.Lookup(fName)
	if n := sym.Def; n != nil {
		return n.(*ir.Name).Func
	}

	deepCopyWrapper := rcGenerateFuncDecl(fn, fName)

	// pItab := (*uintptr)((*eface)(unsafe.Pointer(&src))._type)
	// iData := (*uintptr)(nil)
	// var resTmp interface{}
	// resTmp = eface{pItab, iData}
	// if tcTypeToType(src, &resTmp, false, tcDeepCopy) != nil {
	//   return deepcopy.Copy(src)
	// }
	// return resTmp
	po := ir.ParamNames(deepCopyWrapper.Nname.Type())
	pItab := ir.NewUnaryExpr(fn.Pos(), ir.OITAB, po[0])
	pItab.SetType(types.Types[types.TUINTPTR].PtrTo())
	pItab.SetTypecheck(1)
	iData := ir.NewNilExpr(fn.Pos(), types.Types[types.TUINTPTR].PtrTo())
	iData.SetTypecheck(1)
	typ := ir.NewBinaryExpr(base.Pos, ir.OMAKEFACE, pItab, iData)
	typ.SetType(po[0].Type())
	typ.SetTypecheck(1)
	resTmp := typecheck.TempAt(fn.Pos(), deepCopyWrapper, po[0].Type())
	// It is necessary to add the corresponding resDcl for escape analysis, so that resDcl can be judged as an escape.
	resDcl := ir.NewDecl(fn.Pos(), ir.ODCL, resTmp)
	var resTmpAs ir.Node = ir.NewAssignStmt(fn.Pos(), resTmp, typ)
	resTmpAs = typecheck.Stmt(resTmpAs)

	errTmp := typecheck.TempAt(fn.Pos(), deepCopyWrapper, types.ErrorType)

	replaceFunc := ir.NewBasicLit(fn.Pos(), types.Types[types.TUINT8],
		constant.MakeUint64(uint64(rcFunctionMap[fn.Sym().Name])))
	conv := typecheck.Conv(ir.NewAddrExpr(fn.Pos(), resTmp), types.Types[types.TINTER]).(*ir.ConvExpr)
	conv.TypeWord = typecheck.LinksymAddr(fn.Pos(), types.TypeSym(conv.X.Type()).Linksym(), types.Types[types.TUINT8])
	var errAs ir.Node = ir.NewAssignStmt(fn.Pos(), errTmp, typecheck.Call(fn.Pos(),
		typecheck.LookupRuntime("tcTypeToType"),
		[]ir.Node{po[0], conv, ir.NewBool(fn.Pos(), false), replaceFunc}, false))
	errAs = typecheck.Stmt(errAs)

	nilErr := ir.NewNilExpr(fn.Pos(), types.ErrorType)
	hasErr := ir.NewBinaryExpr(fn.Pos(), ir.ONE, errTmp, nilErr)
	ifs := ir.NewIfStmt(fn.Pos(), hasErr, []ir.Node{ir.NewReturnStmt(fn.Pos(),
		[]ir.Node{typecheck.Call(fn.Pos(), fn.Nname, po, false)})}, nil)
	deepCopyWrapper.Body = []ir.Node{resDcl, resTmpAs, errAs, ifs, ir.NewReturnStmt(fn.Pos(),
		[]ir.Node{resTmp})}

	rcFinishGeneration(deepCopyWrapper, sym)
	return deepCopyWrapper
}

func rcHitReplacement(node ir.Node) int {
	idx, ok := rcFunctionMap[node.Sym().Name]
	if !ok {
		return -1
	}
	if rcPackages[idx] == "" {
		return -1
	}
	if !strings.Contains(base.Ctxt.PosTable.Pos(node.Pos()).Filename(), rcPackages[idx]+"@") &&
		!strings.Contains(base.Ctxt.PosTable.Pos(node.Pos()).Filename(), rcPackages[idx]+string(filepath.Separator)) {
		return -1
	}
	return idx
}

func (v *hairyVisitor) rcMakeReplacedFuncNotInlinable(fn *ir.Func) {
	if rcHitReplacement(fn) == -1 {
		return
	}
	v.budget = 0
}
